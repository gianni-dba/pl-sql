-- piccolo db logistica, tabelle, Foreign Key e indici sulle FK
-- ============================================================================

DROP TABLE Transito CASCADE CONSTRAINTS;
DROP TABLE Gestione CASCADE CONSTRAINTS;
DROP TABLE Magazzino CASCADE CONSTRAINTS;
DROP TABLE Spedizione CASCADE CONSTRAINTS;
DROP TABLE Corriere CASCADE CONSTRAINTS;
DROP TABLE Cliente CASCADE CONSTRAINTS;
DROP TABLE Log_Sped CASCADE CONSTRAINTS;

CREATE TABLE Cliente (
    Codice_Cliente   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nome             VARCHAR2(100) NOT NULL,
    Cognome          VARCHAR2(100),
    Ragione_Sociale  VARCHAR2(200),
    Indirizzo        VARCHAR2(200) NOT NULL,
    Citta            VARCHAR2(50) NOT NULL,
    CAP              VARCHAR2(10),
    Telefono         VARCHAR2(20),
    Email            VARCHAR2(100)
);

CREATE TABLE Corriere (
    Codice_Corriere  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nome             VARCHAR2(50) NOT NULL,
    Cognome          VARCHAR2(50) NOT NULL,
    Mezzo_Trasporto  VARCHAR2(30) NOT NULL,
    Attivo           CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT chk_attivo CHECK (Attivo IN ('S', 'N')),
    CONSTRAINT chk_mezzo CHECK (Mezzo_Trasporto IN ('FURGONE', 'CAMION', 'MOTO', 'BICICLETTA', 'AUTO'))
);

CREATE TABLE Magazzino (
    Codice_Magazzino  VARCHAR2(10) PRIMARY KEY,
    Citta             VARCHAR2(50) NOT NULL,
    Indirizzo         VARCHAR2(200),
    Capacita_Max_Kg   NUMBER(10,2) NOT NULL
);

-- Peso nullable per test anomalie; inserito PRONTO_PARTENZA per test 
CREATE TABLE Spedizione (
    Codice_Spedizione       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Data_Spedizione         DATE DEFAULT SYSDATE NOT NULL,
    Data_Consegna_Prevista  DATE NOT NULL,
    Data_Consegna_Effettiva DATE,
    Peso                    NUMBER(10,2),
    Volume                  NUMBER(10,2),
    Valore_Dichiarato       NUMBER(10,2),
    Codice_Mittente         NUMBER NOT NULL,
    Codice_Destinatario     NUMBER NOT NULL,
    Stato_Spedizione        VARCHAR2(30) DEFAULT 'CREATA' NOT NULL,
    CONSTRAINT chk_stato_sped CHECK (
        Stato_Spedizione IN ('CREATA', 'PRESA_IN_CARICO', 'PRONTO_PARTENZA', 'IN_TRANSITO', 'IN_CONSEGNA', 'CONSEGNATA', 'RESPINTA', 'SMARRITA')
    ),
    CONSTRAINT fk_mittente FOREIGN KEY (Codice_Mittente) REFERENCES Cliente(Codice_Cliente),
    CONSTRAINT fk_destinatario FOREIGN KEY (Codice_Destinatario) REFERENCES Cliente(Codice_Cliente),
    CONSTRAINT chk_date_consegna CHECK (Data_Consegna_Effettiva IS NULL OR Data_Consegna_Effettiva >= Data_Spedizione)
);

-- Assegnazione Corriere - Spedizione
CREATE TABLE Gestione (
    Codice_Corriere    NUMBER NOT NULL,
    Codice_Spedizione  NUMBER NOT NULL,
    Data_Assegnazione  DATE DEFAULT SYSDATE NOT NULL,
    Ruolo              VARCHAR2(30) NOT NULL,
    PRIMARY KEY (Codice_Corriere, Codice_Spedizione),
    CONSTRAINT fk_gest_corriere FOREIGN KEY (Codice_Corriere) REFERENCES Corriere(Codice_Corriere),
    CONSTRAINT fk_gest_spedizione FOREIGN KEY (Codice_Spedizione) REFERENCES Spedizione(Codice_Spedizione)
);

CREATE TABLE Transito (
    Codice_Spedizione  NUMBER NOT NULL,
    Codice_Magazzino   VARCHAR2(10) NOT NULL,
    Data_Arrivo        DATE,
    Data_Partenza      DATE,
    Stato              VARCHAR2(30) NOT NULL,
    PRIMARY KEY (Codice_Spedizione, Codice_Magazzino),
    CONSTRAINT fk_trans_spedizione FOREIGN KEY (Codice_Spedizione) REFERENCES Spedizione(Codice_Spedizione),
    CONSTRAINT fk_trans_magazzino FOREIGN KEY (Codice_Magazzino) REFERENCES Magazzino(Codice_Magazzino),
    CONSTRAINT chk_stato_transito CHECK (Stato IN ('IN_ARRIVO', 'IN_DEPOSITO', 'IN_PARTENZA', 'COMPLETATO')),
    CONSTRAINT chk_date_transito CHECK (
        (Data_Arrivo IS NOT NULL AND Data_Partenza IS NOT NULL AND Data_Partenza >= Data_Arrivo) OR
        (Data_Arrivo IS NOT NULL AND Data_Partenza IS NULL) OR
        (Data_Arrivo IS NULL AND Data_Partenza IS NULL)
    )
);

CREATE GLOBAL TEMPORARY TABLE Log_Sped (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Sped      NUMBER,
    Stato        VARCHAR2(30),
    Descrizione  VARCHAR2(200)
) ON COMMIT PRESERVE ROWS;

-- ============================================================================
-- Indici sulle Foreign Key (Prevenzione table lock in caso di DML sulle padre)
-- ============================================================================
CREATE INDEX idx_sped_mittente ON Spedizione(Codice_Mittente);
CREATE INDEX idx_sped_destinatario ON Spedizione(Codice_Destinatario);
CREATE INDEX idx_gest_sped ON Gestione(Codice_Spedizione);
CREATE INDEX idx_trans_mag ON Transito(Codice_Magazzino);
